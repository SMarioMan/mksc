#!/usr/bin/env python3
"""Generate 8-bpp player labels, native balloon silhouettes and minimap dots.

Only nonzero multiples of 16 are used as colors. Those OBJ palette entries
are transparent in every native 4-bpp sprite, leaving kart palettes intact.
"""
import ast
import hashlib
from pathlib import Path
import struct

root = Path(__file__).resolve().parents[2]
rom = (root / 'baserom.gba').read_bytes()
assert hashlib.sha1(rom).hexdigest() == '9d327c030c3e2d9007990518594f70c3340ac56f'
font_tree = ast.parse((Path(__file__).parent / 'font.py').read_text())
font_node = next(node.value for node in font_tree.body if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'rows' for t in node.targets))
font = {ast.literal_eval(key): ast.literal_eval(value) for key, value in zip(font_node.keys, font_node.values) if isinstance(value, ast.List)}

def lz(offset):
    size = int.from_bytes(rom[offset+1:offset+4], 'little')
    assert rom[offset] == 0x10
    result, offset = bytearray(), offset + 4
    while len(result) < size:
        flags = rom[offset]; offset += 1
        for bit in range(7, -1, -1):
            if len(result) >= size:break
            if flags & (1 << bit):
                a,b=rom[offset:offset+2];offset+=2
                for _ in range((a>>4)+3):result.append(result[-(((a&15)<<8|b)+1)])
            else:result.append(rom[offset]);offset+=1
    assert len(result)==size
    return result

native = lz(0x6D12C)[0x100:0x140]
palette = struct.unpack_from('<16H',rom,0x6D00C+32)
brightness = [sum((color >> shift) & 31 for shift in (0,5,10)) for color in palette]
lightest = max(range(1,16), key=brightness.__getitem__)

def tiled(pixels):
    height,width=len(pixels),len(pixels[0])
    return bytes(pixels[y+row][x+col] for y in range(0,height,8) for x in range(0,width,8) for row in range(8) for col in range(8))

art=[]
for player in range(8):
    pixels=[[0]*16 for _ in range(8)]
    for start,letter in ((2,'P'),(8,str(player+1))):
        for y,row in enumerate(font[letter]):
            for x,bit in enumerate(row):
                if bit=='1' and y+1<8 and start+x+1<16:pixels[y+1][start+x+1]=160
        for y,row in enumerate(font[letter]):
            for x,bit in enumerate(row):
                if bit=='1':pixels[y][start+x]=16*(player+1)
    art.append(tiled(pixels))
for player in range(8):
    pixels=[[0]*8 for _ in range(16)]
    for y in range(16):
        for x in range(8):
            pixel=native[(y//8)*32+(y&7)*4+x//2] >> ((x&1)*4) & 15
            if pixel:pixels[y][x]=144 if pixel==lightest else 160 if brightness[pixel]<15 else 16*(player+1)
    art.append(tiled(pixels))
for player in range(8):
    pixels=[[0]*8 for _ in range(8)]
    for y in range(2):
        for x in range(2):pixels[y][x]=16*(player+1)
    art.append(tiled(pixels))
text=['/* Generated by tools/ring/generate_identity_art.py; 8-bpp, tile order. */', 'static const u16 sIdentityArt[24][64] ALIGNED(4) = {']
for index,data in enumerate(art):
    text.append('    { /* '+('P'+str(index+1) if index<8 else 'balloon '+str(index-7) if index<16 else 'dot '+str(index-15))+' */')
    words=struct.unpack('<'+'H'*(len(data)//2),data)
    for offset in range(0,len(words),8):text.append('        '+','.join(f'0x{word:04X}' for word in words[offset:offset+8])+',')
    text.append('    },')
text.append('};')
(root/'src/ringIdentityArt.h').write_text('\n'.join(text)+'\n')
print('Generated 24 identity graphics without reusing native kart palette colors')
